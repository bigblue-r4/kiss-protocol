func TestSecretFileRoundTrip(t *testing.T) {
	path := filepath.Join(t.TempDir(), "data.key")
	if err := CreateFile(path); err != nil {
		t.Fatal(err)
	}
	keys, err := LoadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	again, err := LoadFile(path)
	if err != nil || keys != again {
		t.Fatalf("keys changed on reload: %v", err)
	}
	if keys.Encryption == keys.MAC {
		t.Fatal("encryption and MAC keys must differ")
	}
	sealed, err := encrypt.Seal([]byte("protected evidence"), keys.Encryption[:])
	if err != nil {
		t.Fatal(err)
	}
	plain, err := encrypt.Open(sealed, again.Encryption[:])
	if err != nil || string(plain) != "protected evidence" {
		t.Fatalf("round trip: %v", err)
	}
	other := filepath.Join(t.TempDir(), "other.key")
	if err := CreateFile(other); err != nil {
		t.Fatal(err)
	}
	wrong, err := LoadFile(other)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := encrypt.Open(sealed, wrong.Encryption[:]); err == nil {
		t.Fatal("unrelated secret decrypted ciphertext")
	}
	legacy, err := encrypt.DeriveKey("known-machine-id")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := encrypt.Open(sealed, legacy); err == nil {
		t.Fatal("machine identity decrypted secret-backed ciphertext")
	}
	// Restoring the same secret at a different path must restore both keys.
	backup, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	restored := filepath.Join(t.TempDir(), "restored.key")
	if err := os.WriteFile(restored, backup, 0400); err != nil {
		t.Fatal(err)
	}
	recovered, err := LoadFile(restored)
	if err != nil || recovered != keys {
		t.Fatalf("restored secret did not recover keys: %v", err)
	}
}

func TestLoadRejectsUnsafeSecretsWithoutChangingThem(t *testing.T) {
	for _, tc := range []struct {
		name string
		size int
		mode os.FileMode
	}{
		{"empty", 0, 0600}, {"short", 31, 0600}, {"long", 33, 0600},
		{"group-readable", 32, 0640}, {"world-readable", 32, 0604},
		{"group-writable", 32, 0620},
	} {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "secret")
			before := bytes.Repeat([]byte{0x42}, tc.size)
			if err := os.WriteFile(path, before, 0600); err != nil {
				t.Fatal(err)
			}
			if err := os.Chmod(path, tc.mode); err != nil {
				t.Fatal(err)
			}
			if _, err := LoadFile(path); err == nil {
				t.Fatal("accepted unsafe secret")
			}
			after, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(before, after) {
				t.Fatal("loading modified the secret")
			}
		})
	}
	missing := filepath.Join(t.TempDir(), "missing")
	if _, err := LoadFile(missing); err == nil {
		t.Fatal("accepted missing secret")
	}
	if _, err := os.Stat(missing); !os.IsNotExist(err) {
		t.Fatalf("loading created missing secret: %v", err)
	}
}

func TestRejectSymlinksAndSpecialFiles(t *testing.T) {
	dir := t.TempDir()
	secret := filepath.Join(dir, "secret")
	if err := CreateFile(secret); err != nil {
		t.Fatal(err)
	}
	before, err := os.ReadFile(secret)
	if err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(dir, "link")
	if err := os.Symlink(secret, link); err != nil {
		t.Fatal(err)
	}
	if _, err := LoadFile(link); err == nil {
		t.Fatal("accepted symlink")
	}
	if err := CreateFile(link); err == nil {
		t.Fatal("created secret through symlink")
	}
	after, err := os.ReadFile(secret)
	if err != nil || !bytes.Equal(before, after) {
		t.Fatal("symlink target changed")
	}
	fifo := filepath.Join(dir, "fifo")
	if err := unix.Mkfifo(fifo, 0600); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{dir, fifo} {
		if _, err := LoadFile(path); err == nil {
			t.Fatalf("accepted special file: %s", path)
		}
	}
}

func TestConcurrentCreateNeverReplacesSecret(t *testing.T) {
	path := filepath.Join(t.TempDir(), "secret")
	var wg sync.WaitGroup
	results := make(chan error, 8)
	for range 8 {
		wg.Go(func() { results <- CreateFile(path) })
	}
	wg.Wait()
	close(results)
	successes := 0
	for err := range results {
		if err == nil {
			successes++
		}
	}
	if successes != 1 {
		t.Fatalf("successful creators: %d", successes)
	}
	before, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := CreateFile(path); err == nil {
		t.Fatal("replaced existing secret")
	}
	after, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(before, after) {
		t.Fatal("existing secret changed")
	}
	if _, err := LoadFile(path); err != nil {
		t.Fatal(err)
	}
}

// Known-answer vectors are computed independently with RFC 5869's HMAC
// extract/expand steps for a fixed fixture, not generated by this package.
func TestDerivationVector(t *testing.T) {
	path := filepath.Join(t.TempDir(), "secret")
	secret := make([]byte, 32)
	for i := range secret {
		secret[i] = byte(i)
	}
	if err := os.WriteFile(path, secret, 0400); err != nil {
		t.Fatal(err)
	}
	keys, err := LoadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		got  []byte
		want string
	}{
		{keys.Encryption[:], "db1e15409ed917eff382ca9ebdd684cc53ef64c8d4c81d60651e0032cf19a493"},
		{keys.MAC[:], "2547cdcbc1be31f5a14897def9ff23a4232dc0d81b8c280c08a3f900db918e63"},
	} {
		if hex.EncodeToString(tc.got) != tc.want {
			t.Fatalf("unexpected derived key: %x", tc.got)
		}
	}
}
